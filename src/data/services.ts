/** Пункт списку в попапі: просто текст або текст із ціною */
export type DetailItem = string | { label: string; price: string };

export type DetailGroup = {
  /** Великий заголовок групи (напр. «Офіси») */
  title?: string;
  /** Підзаголовок/назва підгрупи */
  subtitle?: string;
  items: DetailItem[];
  /** Примітка під групою (мінімальний виїзд тощо) */
  note?: { label: string; value: string };
  /** Особливе розташування в сітці (для довгих попапів) */
  className?: string;
};

export type ServiceId = "general" | "regular" | "repair" | "windows" | "office" | "drycleaning";

export type Service = {
  id: ServiceId;
  /** Назва з переносами, як у дизайні */
  titleLines: string[];
  name: string;
  /** Ціна разового замовлення */
  price?: string;
  /** Ціна за підпискою (якщо є) */
  subscriptionPrice?: string;
  /** Мінімальна ціна в грн для Schema.org */
  priceFrom?: number;
  priceUnit?: string;
  image: StaticImageData;
  /** Варіант фону картки (відтворює оригінальне позиціонування зображень) */
  bg: "cover" | "cover-offset" | "fit-height";
  /** Затемнення зверху (як у картці генерального прибирання) */
  shade?: boolean;
  description: string;
  details: {
    layout: "grid" | "columns";
    /** Великий заголовок над усім списком */
    heading?: string;
    groups: DetailGroup[];
  };
};

